import { useEffect } from 'react'
import { motion, AnimatePresence } from 'motion/react'
import { GlassCard, Button } from './ui'
import Icon from './Icon'

/**
 * Privacy Policy, Terms of Service & India DPDP Act 2023 disclosures modal.
 */
export default function LegalInfoModal({ isOpen, onClose }) {
  useEffect(() => {
    if (!isOpen) return undefined
    const onKey = e => {
      if (e.key === 'Escape') onClose?.()
    }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [isOpen, onClose])

  if (!isOpen) return null

  return (
    <AnimatePresence>
      <div
        className="fixed inset-0 z-50 flex items-center justify-center bg-black/65 p-4 backdrop-blur-md"
        onClick={onClose}
      >
        <motion.div
          initial={{ opacity: 0, scale: 0.96, y: 12 }}
          animate={{ opacity: 1, scale: 1, y: 0 }}
          exit={{ opacity: 0, scale: 0.96, y: 12 }}
          onClick={e => e.stopPropagation()}
          className="w-full max-w-2xl max-h-[85vh] overflow-y-auto"
        >
          <GlassCard className="p-6 sm:p-8 space-y-5 border border-line">
            <div className="flex items-start justify-between gap-4 border-b border-line pb-4">
              <div className="flex items-center gap-3">
                <div className="grid size-10 place-items-center rounded-xl bg-violet-glow/20 text-violet-300 ring-1 ring-line">
                  <Icon name="lock" size={20} />
                </div>
                <div>
                  <h3 className="font-display text-xl font-bold text-fg">Privacy Policy &amp; Terms of Service</h3>
                  <p className="text-xs text-muted">Warranty Agent · Consumer Data Protection &amp; DPDP Act Compliance</p>
                </div>
              </div>
              <button
                type="button"
                onClick={onClose}
                aria-label="Close"
                className="rounded-lg p-1.5 text-subtle hover:bg-glass hover:text-fg transition"
              >
                <Icon name="x" size={18} />
              </button>
            </div>

            <div className="space-y-4 text-xs leading-relaxed text-muted">
              <section className="space-y-1.5">
                <h4 className="text-sm font-semibold text-fg">1. Data We Collect &amp; How It Is Protected</h4>
                <p>
                  Warranty Agent extracts only purchase metadata needed to track warranties (product name, brand,
                  retailer, purchase date, price, warranty dates, return window, and optional masked card last-4 digits).
                  Raw Gmail or forwarded email bodies are processed transiently in memory and are <strong>never</strong>{' '}
                  stored in our database.
                </p>
                <p>
                  Google OAuth refresh tokens (if you connect Gmail) are encrypted at rest with Fernet symmetric
                  encryption and restricted strictly to <code className="font-mono text-fg">gmail.readonly</code>. API
                  requests are authenticated with signed HS256 session tokens.
                </p>
              </section>

              <section className="space-y-1.5">
                <h4 className="text-sm font-semibold text-fg">2. Your Rights (India DPDP Act, 2023)</h4>
                <p>
                  You can inspect, edit, or delete any individual purchase record at any time. To erase everything
                  (your user profile, purchases, uploaded invoices, alerts, WhatsApp link, and forwarding inbox), click{' '}
                  <strong>Delete Account</strong> in the sidebar. Deletion is immediate and permanent.
                </p>
              </section>

              <section className="space-y-1.5">
                <h4 className="text-sm font-semibold text-fg">3. Terms &amp; Self-Help Disclaimers</h4>
                <p>
                  Estimated warranty dates, festival price drop estimates, and credit-card perk summaries are provided
                  for informational convenience — always verify coverage against your original warranty card and bank
                  benefit guide.
                </p>
                <p>
                  Pre-litigation notices and NCH / e-Jagriti drafts generated by the Legal Notice tool are self-help
                  consumer templates prepared under the Consumer Protection Act, 2019 and do not constitute formal
                  legal advice or an advocate-client relationship.
                </p>
              </section>
            </div>

            <div className="flex justify-end border-t border-line pt-4">
              <Button variant="secondary" size="md" onClick={onClose}>
                Close
              </Button>
            </div>
          </GlassCard>
        </motion.div>
      </div>
    </AnimatePresence>
  )
}

